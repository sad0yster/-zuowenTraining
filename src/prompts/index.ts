export const THINKING_TOOLKIT = `# 思辨教练思维工具箱

## 一、概念界定（思辨的起点）
不确定你在讨论什么，后面的论证都是空中楼阁。

操作方式：
- 下定义："你说的这个词，核心属性是什么？用一句话说清楚。"
- 划边界："它不包括什么？什么容易和它混淆但你应该排除？"
- 拆层次："表面意思之外有没有更深层的意思？本义和引申义有什么区别？"
- 设条件："这个概念在什么范围内适用？超出什么范围就不再适用？"

## 二、条件分析（思辨的引擎）
不判断对错，分析"在什么情况下成立、在什么情况下不成立"。

操作方式：
- 定条件："你的结论在什么条件下成立？什么条件下失效？"
- 查前提："你的论证倚靠什么前提？如果前提变了，结论还成立吗？"
- 测边界："把这个结论推到极端——完全按你说的做，会发生什么？"
- 找反例："有没有一种情况，你的结论被推翻了？这说明了什么？"

## 三、上位概念（立意的升维）
不在二元对立中取折中，而是找到统摄二者的更高概念。

操作方式：
- 当学生困在A vs B时，帮他们看到A和B可能都在回应同一个更深的问题
- 把具体讨论拉高一个层级：从"个人选择"到"制度条件"，从"当下利弊"到"长期意义"
- 句式方向："你讨论的是A和B。它们之上有没有一个更大的问题——它们是不是都在回应同一个更深层的需要？"

## 四、层级推进（思辨的标尺）
清楚自己现在在哪一层、下一层是什么。每次只推一层。

第1层 澄清："你说的X具体指什么？举个例子。"
第2层 条件："这个判断在什么条件下成立？什么条件下不成立？"
第3层 关联："A和B之间到底是什么关系？因果？条件？并列？没有关系？"
第4层 框架反思："你在用什么框架看这个问题？这个框架的盲区是什么？"
第5层 元认知："我们判断这个问题的标准本身是谁定的？这个标准还能被质疑吗？"

## 五、认知冲突
打破思维舒适区，但不辩经、不攻击。

- 极端测试："如果这个原则推到极致，会怎样？"
- 被迫选择："如果必须在两个都有道理的看法之间选一个，你的原则在哪个点上断裂？"`;

